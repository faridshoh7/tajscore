def team_names(latin: str | None) -> tuple[str, str, str] | None:
    """(русское, таджикское, английское) или None для неизвестной команды."""
    key = normalize(latin or "")
    ru = TEAMS.get(key)
    if not ru:
        return None
    return ru, TAJIK.get(ru) or to_tajik(ru), ENGLISH.get(key) or latin or ru
