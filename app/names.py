"""Русские и таджикские названия команд.

Оба источника отдают названия латиницей и в своём написании: «Bayern München»,
«Internazionale», «Spain». Для сайта с русской и таджикской аудиторией это
нечитаемо, а транслитерация тут не работает: русские названия клубов
договорные, а не фонетические. «Bayern» — это Бавария, «Inter» — Интер,
«Spain» — Испания; побуквенный перевод дал бы «Байерн», «Интернационале»,
«Спаин». Поэтому здесь ручной справочник.

Таджикское написание выводится из русского автоматически (to_tajik): в
таджикском алфавите нет ц, щ, ы и ь, остальные буквы те же. Для слов, где
таджикский язык использует собственное название, а не заимствование, есть
отдельная таблица TAJIK.

Клубы Лигаи Олӣ сюда не входят — у них свой выверенный справочник
в app/teams_tj.py, и он имеет приоритет.
"""
import re

