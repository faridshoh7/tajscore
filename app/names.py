# Буквы, которых нет в таджикском алфавите. Для заимствованных названий
# («Манчестер Юнайтед») этого достаточно: ғ, қ, ӯ, ҳ, ҷ, ӣ ставятся в исконных
# словах, а не в переданных с другого языка.
_TJ_MAP = str.maketrans({"ы": "и", "Ы": "И",
                         "ц": "с", "Ц": "С",
                         "щ": "ш", "Щ": "Ш",
                         "ь": "", "Ь": ""})


def to_tajik(ru: str) -> str:
    """Русское написание -> таджикское.

    Аббревиатуры не трогаем: «ЦСКА» по правилу ц->с превратился бы в «ССКА»,
    а читается он одинаково на обоих языках. Признак — слово целиком заглавными.
    """
    if not ru:
        return ""
    return _WORD.sub(lambda m: m.group(0) if _is_abbr(m.group(0))
                     else m.group(0).translate(_TJ_MAP), ru)


_WORD = re.compile(r"[^\W\d_]+", re.UNICODE)


def _is_abbr(w: str) -> bool:
    return len(w) > 1 and w.isupper()


